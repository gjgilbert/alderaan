"""Run every per-algorithm harness in one process, sharing pipeline state.

Harnesses run in order of the last pipeline step each profiles, so each step's
profiled output is the next harness's input: setup builds only the steps ahead
of quick_fit_transit_shape, once, instead of every harness rebuilding the
pipeline (two DetrendVisits passes and RegularizeOMC) from scratch.

Ends with a summary report ranking algorithms by profiled wall-clock (both
pipeline passes combined; data I/O and plots are in ``profile_pipeline.py``).

Run with ``make profile`` or ``python tests/profiling/profile_all.py``.
"""

from datetime import UTC, datetime

try:  # importable via `-m tests.profiling.profile_*` or runnable as a script
    from tests.profiling import _profiling as P
    from tests.profiling import (
        profile_clip_outliers,
        profile_detrend_visits,
        profile_flag_bad_transits,
        profile_quick_fit_transit_shape,
        profile_quick_fit_transit_times,
        profile_regularize_omc,
        profile_sample_transit_model,
    )
except ModuleNotFoundError:
    import _profiling as P
    import profile_clip_outliers
    import profile_detrend_visits
    import profile_flag_bad_transits
    import profile_quick_fit_transit_shape
    import profile_quick_fit_transit_times
    import profile_regularize_omc
    import profile_sample_transit_model

HARNESSES = [
    profile_quick_fit_transit_shape,
    profile_quick_fit_transit_times,
    profile_regularize_omc,
    profile_clip_outliers,
    profile_detrend_visits,
    profile_flag_bad_transits,
    profile_sample_transit_model,
]


def run():
    seconds = {}
    for harness in HARNESSES:
        name = harness.__name__.rsplit(".", 1)[-1].removeprefix("profile_")
        seconds[name] = harness.run()

    total = sum(seconds.values())
    ts = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    out = [
        "# Profiling report: summary (all algorithms)",
        "",
        f"_Generated {ts} • profiled wall-clock: {total:.3f} s_",
        "",
        "> Auto-generated by `tests/profiling/profile_all.py`. Profiled wall-clock "
        "per algorithm (both pipeline passes combined); function-level detail is in "
        f"each algorithm's report. {P._SAMPLERS_NOTE}",
        "",
        "| algorithm | % | s |",
        "|---|---:|---:|",
    ]
    for name, secs in sorted(seconds.items(), key=lambda e: e[1], reverse=True):
        out.append(f"| `{name}` | {secs / total:.1%} | {secs:.3f} |")
    report = "\n".join(out)
    print(report)
    P._write_report(report, "summary")


if __name__ == "__main__":
    run()
